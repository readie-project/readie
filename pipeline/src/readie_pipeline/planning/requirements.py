"""The distributions a plan needs installed in the rootfs.

A checkpoint pre-imports modules; a module can only be imported from a rootfs
that has its distribution installed. This turns a plan into that list, so a rootfs
built from a minimal base can carry exactly what the checkpoints (and so the
requests they serve) use. It is independent of the planner: it reads whatever
``CheckpointPlan`` entries a planner produced.

Each line pins the version the metadata recorded for the distribution (the one
installed in the image the metadata was measured in), so the rootfs gets the
packages whose import times and sizes the plan was built from. A distribution the
metadata has no version for is listed by name and takes whatever the package index
resolves. The Dockerfile's ``rootfs`` stage applies the executor's locked versions
as constraints (see there).
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path

from readie_pipeline.metadata.models import Metadata, PackageFacts
from readie_pipeline.planning.ports import CheckpointPlan

#: File name beside the plan. The Dockerfile's ``ROOTFS_REQUIREMENTS`` build
#: argument points at it.
REQUIREMENTS_FILE = "rootfs-requirements.txt"


def _facts_for(name: str, metadata: Metadata) -> PackageFacts | None:
    """Facts for ``name``, or for its closest dotted parent that has any.

    A module a package loads (``numpy.core._multiarray_umath``) usually has no
    entry of its own; the package it sits under (``numpy``) does.
    """
    parts = name.split(".")
    for end in range(len(parts), 0, -1):
        facts = metadata.get(".".join(parts[:end]))
        if facts is not None:
            return facts
    return None


def distributions_for(plans: Iterable[CheckpointPlan], metadata: Metadata) -> tuple[str, ...]:
    """Every distribution the plans' imports, and what those load, come from.

    Sorted and without duplicates. A module that belongs to no distribution (the
    standard library) or that the metadata knows nothing about adds nothing.
    """
    imports = {name for plan in plans for name in plan.imports}
    found: set[str] = set()
    for module in metadata.closure(imports):
        facts = _facts_for(module, metadata)
        if facts is not None and facts.distribution:
            found.add(facts.distribution)
    return tuple(sorted(found))


def requirement_lines(distributions: Iterable[str], metadata: Metadata) -> tuple[str, ...]:
    """Each distribution as ``name==version``, or the bare name when no version is known."""
    lines = []
    for name in distributions:
        version = metadata.version_of(name)
        lines.append(f"{name}=={version}" if version else name)
    return tuple(lines)


def write_requirements(path: Path, requirements: Iterable[str]) -> None:
    """Write one requirement per line, with a header the installer skips."""
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "# Distributions installed into the rootfs, pinned to the versions in the metadata.",
        "# Generated by `readie-pipeline plan`.",
    ]
    lines.extend(requirements)
    path.write_text("\n".join(lines) + "\n")
